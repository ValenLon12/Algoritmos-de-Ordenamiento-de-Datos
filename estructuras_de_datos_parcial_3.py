def merge_sort(arr):
    if len(arr) > 1:
        medio = len(arr) // 2
        izq = arr[:medio]
        der = arr[medio:]
        merge_sort(izq)
        merge_sort(der)
        i = j = k = 0
        while i < len(izq) and j < len(der):
            if izq[i] < der[j]:
                arr[k] = izq[i]; i += 1
            else:
                arr[k] = der[j]; j += 1
            k += 1
        while i < len(izq): arr[k] = izq[i]; i += 1; k += 1
        while j < len(der): arr[k] = der[j]; j += 1; k += 1

