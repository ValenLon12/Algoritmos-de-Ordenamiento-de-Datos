def quick_sort(arr):
    if len(arr) <= 1:
        return arr
    pivote = arr[len(arr) // 2]
    return quick_sort([x for x in arr if x < pivote]) + [x for x in arr if x == pivote] + quick_sort([x for x in arr if x > pivote])

inicio = time.time()
datos_ordenados = quick_sort(datos)
fin = time.time()

print("--- QUICK SORT ---")
