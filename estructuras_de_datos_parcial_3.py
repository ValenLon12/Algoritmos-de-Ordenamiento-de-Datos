def insertion_sort(arr):
    for i in range(1, len(arr)):
        clave = arr[i]
        j = i - 1
        while j >= 0 and clave < arr[j]:
            arr[j + 1] = arr[j]
            j -= 1
        arr[j + 1] = clave

inicio = time.time()
insertion_sort(datos)
fin = time.time()

print("--- INSERTION SORT ---")
print(f"Primeros 10 datos ordenados: {datos[:10]}")
