import time
import pandas as pd

df = pd.read_csv('customer_master.csv')
datos = df['customer_postal_code'].dropna().tolist()[:25000]

def bubble_sort(arr):
    n = len(arr)
    for i in range(n):
        for j in range(0, n - i - 1):
            if arr[j] > arr[j + 1]:
                arr[j], arr[j + 1] = arr[j + 1], arr[j]

inicio = time.time()
bubble_sort(datos)
fin = time.time()

print("--- BUBBLE SORT ---")
print(f"Primeros 10 datos ordenados: {datos[:10]}")
print(f"Tiempo: {fin - inicio:.5f} segundos\n")

